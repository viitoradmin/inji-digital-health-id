    ARRAY['fullName', 'policyNumber', 'plan', 'coverageValidUntil'],
    'insurance_vc_ldp',
    ARRAY['did:jwk'],
    ARRAY['Ed25519Signature2020'],
    '{"jwt": {"proof_signing_alg_values_supported": ["RS256", "ES256"]}}'::JSONB,
    '{"fullName": {"display": [{"name": "Full Name", "locale": "en"}]}, "policyNumber": {"display": [{"name": "Policy Number", "locale": "en"}]}, "plan": {"display": [{"name": "Plan", "locale": "en"}]}, "coverageValidUntil": {"display": [{"name": "Valid Until", "locale": "en"}]}}'::JSONB,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    NOW(),
    NULL
);
SQL

echo "Wrote: ${OUT_SQL}"
echo "Wrote: ${SCRIPT_DIR}/dist/contexts/student.json"
echo "Wrote: ${SCRIPT_DIR}/dist/contexts/insurance.json"
echo "Patched did-url in: ${PROPS}"
echo
echo "NEXT STEPS:"
echo "  1. Start the stack so Certify generates its DID document:"
echo "       ./setup.sh && docker compose up -d"
echo "  2. Fetch the DID document and publish it to GitHub Pages at:"
echo "       ${BASE_URL}/inji-issuer/did.json"
echo "     curl -s http://localhost:8090/v1/certify/.well-known/did.json"
echo "  3. Publish the two context files (custom-issuer/dist/contexts/) to:"
echo "       ${STUDENT_CTX_URL}"
echo "       ${INSURANCE_CTX_URL}"
echo "  4. Recreate so the generated SQL is applied (fresh DB):"
echo "       docker compose down -v && ./setup.sh && docker compose up -d"
