-- GENERATED by custom-issuer/generate-config.sh — DO NOT EDIT BY HAND.
-- Re-run the generator to regenerate after changing the host/DID or templates.
--
-- BASE_URL   = ${BASE_URL}
-- ISSUER_DID = ${ISSUER_DID}
--
-- Inserts the credential_config rows for the custom Postgres-backed issuers. Runs after
-- certify_init.sql during Postgres container initialization (alphabetical order).
-- =====================================================================================
\\c inji_certify postgres

-- Issuer 1: University -> StudentIdentityCredential
