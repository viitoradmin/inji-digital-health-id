#!/usr/bin/env bash
# =====================================================================================
# generate-config.sh
#
# Bakes your public GitHub Pages base URL + issuer did:web into:
#   1. certify_init_custom.sql            -> credential_config rows (base64 VC templates)
#   2. config/certify-postgres-custom.properties -> the did-url
#   3. custom-issuer/dist/contexts/*.json -> JSON-LD @context files ready to upload
#
# Why a generator: the VC template is stored base64-encoded in credential_config, and
# the @context URL lives *inside* that template, so it can't be sed-replaced after
# encoding. This script substitutes first, then encodes.
#
# Usage:
#   ./generate-config.sh <BASE_URL> [ISSUER_DID]
#
#   BASE_URL    Public GitHub Pages root, e.g. https://janedoe.github.io/inji-config
#   ISSUER_DID  (optional) issuer did:web. If omitted, derived from BASE_URL as
#               did:web:<host>:<path...>:inji-issuer
#
# Example:
#   ./generate-config.sh https://janedoe.github.io/inji-config
#     -> ISSUER_DID = did:web:janedoe.github.io:inji-config:inji-issuer
#     -> did.json must be hosted at https://janedoe.github.io/inji-config/inji-issuer/did.json
#     -> contexts at https://janedoe.github.io/inji-config/contexts/{student,insurance}.json
# =====================================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STACK_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

BASE_URL="${1:-}"
if [[ -z "${BASE_URL}" ]]; then
  echo "ERROR: BASE_URL is required." >&2
  echo "Usage: $0 <BASE_URL> [ISSUER_DID]" >&2
  echo "Example: $0 https://janedoe.github.io/inji-config" >&2
  exit 1
fi
BASE_URL="${BASE_URL%/}"   # strip trailing slash

# Derive ISSUER_DID from BASE_URL if not provided:
#   https://host/seg1/seg2  ->  did:web:host:seg1:seg2:inji-issuer
if [[ -n "${2:-}" ]]; then
  ISSUER_DID="$2"
else
  no_scheme="${BASE_URL#https://}"
  no_scheme="${no_scheme#http://}"
  ISSUER_DID="did:web:${no_scheme//\//:}:inji-issuer"
fi

STUDENT_CTX_URL="${BASE_URL}/contexts/student.json"
INSURANCE_CTX_URL="${BASE_URL}/contexts/insurance.json"

echo "BASE_URL          = ${BASE_URL}"
echo "ISSUER_DID        = ${ISSUER_DID}"
echo "STUDENT_CTX_URL   = ${STUDENT_CTX_URL}"
echo "INSURANCE_CTX_URL = ${INSURANCE_CTX_URL}"
echo

# ---- 1. Base64-encode the VC templates with the real context URL substituted --------
student_tpl="$(sed "s#__STUDENT_CTX_URL__#${STUDENT_CTX_URL}#g" "${SCRIPT_DIR}/templates/student-identity-vc.json")"
insurance_tpl="$(sed "s#__INSURANCE_CTX_URL__#${INSURANCE_CTX_URL}#g" "${SCRIPT_DIR}/templates/insurance-vc.json")"
STUDENT_B64="$(printf '%s' "${student_tpl}" | base64 -w0)"
INSURANCE_B64="$(printf '%s' "${insurance_tpl}" | base64 -w0)"

# ---- 2. Emit dist context files ready to publish on GitHub Pages --------------------
mkdir -p "${SCRIPT_DIR}/dist/contexts"
sed "s#__BASE_URL__#${BASE_URL}#g" "${SCRIPT_DIR}/context/student.json"   > "${SCRIPT_DIR}/dist/contexts/student.json"
sed "s#__BASE_URL__#${BASE_URL}#g" "${SCRIPT_DIR}/context/insurance.json" > "${SCRIPT_DIR}/dist/contexts/insurance.json"

# ---- 3. Patch the did-url into the Postgres plugin properties ------------------------
PROPS="${STACK_DIR}/config/certify-postgres-custom.properties"
sed -i.bak "s#^mosip.certify.data-provider-plugin.did-url=.*#mosip.certify.data-provider-plugin.did-url=${ISSUER_DID}#" "${PROPS}"
rm -f "${PROPS}.bak"

# ---- 4. Generate certify_init_custom.sql (credential_config rows) -------------------
OUT_SQL="${STACK_DIR}/certify_init_custom.sql"
cat > "${OUT_SQL}" <<SQL
