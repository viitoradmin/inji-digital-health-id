    '[{"name": "University Student ID", "locale": "en", "logo": {"url": "https://mosip.github.io/inji-config/logos/agro-vertias-logo.png", "alt_text": "University Logo"}, "background_color": "#0b3d91", "text_color": "#FFFFFF"}]'::JSONB,
    ARRAY['fullName', 'studentId', 'program', 'enrollmentYear', 'email'],
    'student_vc_ldp',
    ARRAY['did:jwk'],
    ARRAY['Ed25519Signature2020'],
    '{"jwt": {"proof_signing_alg_values_supported": ["RS256", "ES256"]}}'::JSONB,
    '{"fullName": {"display": [{"name": "Full Name", "locale": "en"}]}, "studentId": {"display": [{"name": "Student ID", "locale": "en"}]}, "program": {"display": [{"name": "Program", "locale": "en"}]}, "enrollmentYear": {"display": [{"name": "Enrollment Year", "locale": "en"}]}, "email": {"display": [{"name": "Email", "locale": "en"}]}}'::JSONB,
    NULL,
